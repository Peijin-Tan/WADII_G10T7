import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { enableAutoUnmount } from '@vue/test-utils'
import axios from 'axios'
import Community from '@/views/Community.vue'
import { renderFeature, flushPromises, button, text, comment, like, recipe, serverError, deferred } from './featureTestSupport'

vi.mock('axios', () => ({ default: { get: vi.fn(), put: vi.fn(), delete: vi.fn() } }))
// The Neighbour Pantry tab is its own component with its own API client (createApi -> axios.create),
// so it's replaced with an empty stub here and these tests stay about comments and likes.
vi.mock('@/components/community/NeighbourPantry.vue', () => ({ default: { name: 'NeighbourPantry', render: () => null } }))
enableAutoUnmount(afterEach)
beforeEach(() => {
  vi.resetAllMocks()
  axios.get.mockImplementation(url => {
    if (url === '/activity/comments') return Promise.resolve({ data: [{ ...comment }] })
    if (url === '/activity/likes') return Promise.resolve({ data: [{ ...like }] })
    return Promise.reject(new Error(`Unexpected request: ${url}`))
  })
})
afterEach(() => vi.restoreAllMocks())

// Component tests: exercise the activity page through its rendered controls.
describe('Community: comments and likes', () => {
  it('C01 asks a guest to log in and does not request private data', async () => {
    const { wrapper } = await renderFeature(Community, { loggedIn: false })
    expect(text(wrapper)).toContain('Log in to view your comments and liked recipes.')
    expect(axios.get).not.toHaveBeenCalled()
    expect(wrapper.get('a').attributes('href')).toBe('/login')
  })
  it('C02 displays comments grouped under the same recipe', async () => {
    axios.get.mockImplementation(url => Promise.resolve({ data: url.endsWith('comments')
      ? [{ ...comment }, { ...comment, _id: 'second-comment', content: 'Easy to cook!' }] : [] }))
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    expect(wrapper.findAll('article')).toHaveLength(1)
    expect(text(wrapper)).toContain('Delicious tofu!')
    expect(text(wrapper)).toContain('Easy to cook!')
    expect(text(wrapper)).toContain('2 comments')
  })
  it('C03 shows the comments empty state', async () => {
    axios.get.mockResolvedValue({ data: [] })
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    expect(text(wrapper)).toContain('No comments yet')
  })
  it('C04 switches to liked recipes and links to the recipe detail page', async () => {
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'My Liked Recipes').trigger('click')
    expect(text(wrapper)).toContain(recipe.title)
    expect(text(wrapper)).toContain('1 like')
    const link = wrapper.findAll('a').find(a => a.text() === 'View Recipe')
    expect(link.attributes('href')).toBe(`/recipes/${recipe._id}`)
  })
  it('C05 shows the liked recipes empty state', async () => {
    axios.get.mockResolvedValue({ data: [] })
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'My Liked Recipes').trigger('click')
    expect(text(wrapper)).toContain('No liked recipes yet')
  })
  it('C06 saves trimmed comment text and displays the server result', async () => {
    axios.put.mockResolvedValue({ data: { ...comment, content: 'Updated tofu tip', updatedAt: '2026-11-01T02:00:00Z' } })
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'Edit').trigger('click')
    await wrapper.get('textarea').setValue('  Updated tofu tip  ')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(axios.put).toHaveBeenCalledWith(`/activity/comments/${comment._id}`,
      { content: 'Updated tofu tip' }, { headers: { Authorization: 'Bearer token-a' } })
    expect(text(wrapper)).toContain('Updated tofu tip')
    expect(text(wrapper)).toContain('Your comment was updated.')
    expect(text(wrapper)).toContain('Edited')
    expect(wrapper.find('textarea').exists()).toBe(false)
  })
  it.each([['spaces', '   '], ['over 2000 characters', 'x'.repeat(2001)]])(
    'C07 rejects an edit containing %s', async (_label, content) => {
      const { wrapper } = await renderFeature(Community)
      await flushPromises()
      await button(wrapper, 'Edit').trigger('click')
      await wrapper.get('textarea').setValue(content)
      await wrapper.get('form').trigger('submit')
      expect(axios.put).not.toHaveBeenCalled()
      expect(text(wrapper)).toContain('Comment must contain 1–2000 characters.')
    })
  it.each([1, 2000])('C08 accepts the valid boundary of %i characters', async length => {
    const content = 'x'.repeat(length)
    axios.put.mockResolvedValue({ data: { ...comment, content } })
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'Edit').trigger('click')
    await wrapper.get('textarea').setValue(content)
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(text(wrapper)).toContain('Your comment was updated.')
    expect(axios.put).toHaveBeenCalledTimes(1)
  })
  it('C09 cancels an edit without saving', async () => {
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'Edit').trigger('click')
    await wrapper.get('textarea').setValue('Discard this')
    await button(wrapper, 'Cancel').trigger('click')
    expect(text(wrapper)).toContain(comment.content)
    expect(wrapper.find('textarea').exists()).toBe(false)
    expect(axios.put).not.toHaveBeenCalled()
  })
  it('C10 leaves the comment unchanged when deletion is cancelled', async () => {
    vi.spyOn(window, 'confirm').mockReturnValue(false)
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'Delete').trigger('click')
    expect(axios.delete).not.toHaveBeenCalled()
    expect(text(wrapper)).toContain(comment.content)
  })
  it('C11 removes a comment after confirmed successful deletion', async () => {
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    axios.delete.mockResolvedValue({ data: {} })
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'Delete').trigger('click')
    await flushPromises()
    expect(axios.delete).toHaveBeenCalledWith(`/activity/comments/${comment._id}`,
      { headers: { Authorization: 'Bearer token-a' } })
    expect(text(wrapper)).toContain('No comments yet')
    expect(text(wrapper)).toContain('Your comment was deleted.')
  })
  it('C12 removes an unliked recipe using the Like document ID', async () => {
    axios.delete.mockResolvedValue({ data: {} })
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'My Liked Recipes').trigger('click')
    await button(wrapper, 'Unlike').trigger('click')
    await flushPromises()
    expect(axios.delete).toHaveBeenCalledWith(`/activity/likes/${like._id}`,
      { headers: { Authorization: 'Bearer token-a' } })
    expect(text(wrapper)).toContain('No liked recipes yet')
    expect(text(wrapper)).toContain('Recipe removed from your likes.')
  })
  it('C13 keeps a liked recipe visible when removing it fails', async () => {
    axios.delete.mockRejectedValue(serverError('Cannot remove like'))
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    await button(wrapper, 'My Liked Recipes').trigger('click')
    await button(wrapper, 'Unlike').trigger('click')
    await flushPromises()
    expect(text(wrapper)).toContain('Cannot remove like')
    expect(text(wrapper)).toContain(recipe.title)
    expect(button(wrapper, 'Unlike').attributes('disabled')).toBeUndefined()
  })
  it('C14 displays an expired login message', async () => {
    axios.get.mockRejectedValue(serverError('Unauthorized', 401))
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    expect(text(wrapper)).toContain('Your login has expired. Please log in again.')
  })
  it('C15 retries a failed comments request', async () => {
    axios.get.mockRejectedValueOnce(serverError('Cannot load comments'))
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    expect(text(wrapper)).toContain('Cannot load comments')
    await button(wrapper, 'Try again').trigger('click')
    await flushPromises()
    expect(text(wrapper)).toContain(comment.content)
    expect(text(wrapper)).not.toContain('Cannot load comments')
  })
  it('C16 handles a removed recipe without crashing', async () => {
    axios.get.mockResolvedValue({ data: [{ ...comment, recipeId: null }] })
    const { wrapper } = await renderFeature(Community)
    await flushPromises()
    expect(text(wrapper)).toContain('Recipe no longer available')
    expect(text(wrapper)).toContain(comment.content)
  })
  it('C17 clears the previous account and ignores its late response', async () => {
    const old = deferred()
    axios.get.mockImplementation(url => url.endsWith('comments') ? old.promise : Promise.resolve({ data: [] }))
    const { wrapper, auth } = await renderFeature(Community)
    axios.get.mockResolvedValue({ data: [] })
    auth.setLogin({ token: 'token-b', user: { _id: 'user-b' } })
    await flushPromises()
    old.resolve({ data: [{ ...comment }] })
    await flushPromises()
    expect(text(wrapper)).not.toContain(comment.content)
    expect(text(wrapper)).toContain('No comments yet')
  })
})
